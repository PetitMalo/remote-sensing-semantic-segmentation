"""Render the bash script a training VM runs on first boot.

The script is generated per run so the instance carries no secret and no
metadata to parse: everything the job needs is baked in as shell-quoted
literals. It installs ``uv``, unpacks the commit's code archive, synchronises
the dependencies, runs :mod:`rsss.gcp.job`, then uploads the boot log and shuts
the VM down even when a step fails.
"""

from __future__ import annotations

import shlex

# Fail before training if the image's driver cannot see the GPU. The `gcp`
# dependency group installs CUDA 13 wheels, so an older DLVM image would only
# fail later, at the first tensor kernel.
_CUDA_CHECK = (
    'uv run --no-sync python -c "import torch; '
    "print('torch', torch.__version__, 'cuda', torch.version.cuda, "
    "'available', torch.cuda.is_available()); "
    'raise SystemExit(0 if torch.cuda.is_available() else 1)"'
)


def render_startup_script(
    *,
    bucket: str,
    run_name: str,
    sha: str,
    train_config: str,
    data_config: str,
    epochs: int | None = None,
    resume: bool = False,
    limit_train_batches: float | None = None,
    sync_interval: int = 600,
) -> str:
    """Return the startup script for one run.

    Parameters
    ----------
    bucket : str
        Bucket holding the code archive, the dataset and the runs.
    run_name : str
        Run directory name, also used for the GCS prefix.
    sha : str
        Commit the archive was built from.
    train_config, data_config : str
        Config paths inside the archived repository.
    epochs : int, optional
        Total epoch count; the recipe's value applies when omitted.
    resume : bool
        Continue from ``<run>/checkpoints/last.ckpt`` when it exists.
    limit_train_batches : float, optional
        Cap the training batches per epoch, for a smoke run.
    sync_interval : int
        Seconds between two artefact uploads while training.
    """
    job_args = [
        f"    --bucket {shlex.quote(bucket)}",
        f"    --run {shlex.quote(run_name)}",
        f"    --sha {shlex.quote(sha)}",
        f"    --train-config {shlex.quote(train_config)}",
        f"    --data-config {shlex.quote(data_config)}",
        f"    --sync-interval {sync_interval}",
    ]
    if epochs is not None:
        job_args.append(f"    --epochs {epochs}")
    if resume:
        job_args.append("    --resume")
    if limit_train_batches is not None:
        job_args.append(f"    --limit-train-batches {limit_train_batches}")
    job_block = "\n".join(job_args)

    return f"""#!/bin/bash
# Generated by `python -m rsss.gcp.submit`; edits are overwritten.
set -euo pipefail

BUCKET={shlex.quote(bucket)}
RUN={shlex.quote(run_name)}
SHA={shlex.quote(sha)}

exec > >(tee -a /var/log/rsss-startup.log) 2>&1

cleanup() {{
    status=$?
    gcloud storage cp /var/log/rsss-startup.log \\
        "gs://$BUCKET/runs/$RUN/logs/startup.log" || true
    echo "[rsss] done (status $status); shutting down."
    shutdown -h now || true
}}
trap cleanup EXIT

echo "[rsss] run $RUN from commit $SHA"
if ! command -v uv > /dev/null 2>&1; then
    curl -LsSf https://astral.sh/uv/install.sh | sh
fi
export PATH="$HOME/.local/bin:/usr/local/bin:$PATH"

mkdir -p /opt/rsss /mnt/data /mnt/run
gcloud storage cp "gs://$BUCKET/code/$SHA.tar.gz" /tmp/rsss-code.tar.gz
tar -xzf /tmp/rsss-code.tar.gz -C /opt/rsss
cd /opt/rsss

uv sync --frozen --no-default-groups --no-dev --group gcp
{_CUDA_CHECK}

JOB_ARGS=(
{job_block}
)
uv run --no-sync python -m rsss.gcp.job "${{JOB_ARGS[@]}}"
"""
